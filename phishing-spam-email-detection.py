# ------------------------------------------------------------
# 2. Function for text cleaning
# ------------------------------------------------------------

def clean_robustness_text(text):

    text = str(text).lower()

    text = re.sub(
        r"http\S+|www\S+|https\S+",
        " ",
        text
    )

    text = re.sub(
        r"\S+@\S+",
        " ",
        text
    )

    text = re.sub(
        r"<.*?>",
        " ",
        text
    )

    text = text.translate(
        str.maketrans(
            "",
            "",
            string.punctuation
        )
    )

    text = re.sub(
        r"\d+",
        " ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip()

    return text


# ------------------------------------------------------------
# 3. Create small text modifications
# ------------------------------------------------------------

def add_extra_spaces(text):

    return "  " + text.replace(" ", "   ") + "  "


def change_capitalization(text):

    words = text.split()

    changed = []

    for i, word in enumerate(words):

        if i % 3 == 0:
            changed.append(word.upper())

        else:
            changed.append(word)

    return " ".join(changed)


def add_harmless_words(text):

    return (
        "Please carefully review this message. "
        + text +
        " Thank you."
    )


# ------------------------------------------------------------
# 4. Create original and modified versions
# ------------------------------------------------------------

robustness_data["original"] = (
    robustness_data["text"]
    .apply(clean_robustness_text)
)

robustness_data["extra_spaces"] = (
    robustness_data["text"]
    .apply(add_extra_spaces)
    .apply(clean_robustness_text)
)

robustness_data["capitalization"] = (
    robustness_data["text"]
    .apply(change_capitalization)
    .apply(clean_robustness_text)
)

robustness_data["extra_words"] = (
    robustness_data["text"]
    .apply(add_harmless_words)
    .apply(clean_robustness_text)
)


# ------------------------------------------------------------
# 5. Prediction function
# ------------------------------------------------------------

def get_predictions(texts):

    tfidf_data = tfidf.transform(texts)

    svm_predictions = svm_model.predict(
        tfidf_data
    )

    nb_predictions = nb_model.predict(
        tfidf_data
    )

    rf_predictions = rf_model.predict(
        tfidf_data
    )

    return (
        svm_predictions,
        nb_predictions,
        rf_predictions
    )


# ------------------------------------------------------------
# 6. Get predictions for original emails
# ------------------------------------------------------------

(
    svm_original,
    nb_original,
    rf_original
) = get_predictions(
    robustness_data["original"]
)


# ------------------------------------------------------------
# 7. Get predictions for modified emails
